def save_trajectory_data(action_pred_batch, save_path, format='npz', **kwargs):
    """
    Save trajectory data in different formats.

    Parameters:
    - action_pred_batch: np.ndarray or dict, shape (batch_size, prediction_horizon, action_dim)
                         or dictionary containing trajectory data
    - save_path: str or Path, path to save the trajectory data
    - format: str, 'npz' (default), 'pkl', or 'npy'
    - **kwargs: additional data to save (e.g., init_pos, task_name, etc.)

    Returns:
    - dict: Saved trajectory data dictionary
    """
    from pathlib import Path
    import pickle

    save_path = Path(save_path)
    save_path.parent.mkdir(parents=True, exist_ok=True)

    if isinstance(action_pred_batch, dict):
        # 如果输入是字典，直接使用
        traj_data = action_pred_batch.copy()
        print(f"📦 Saving existing trajectory dictionary with {len(traj_data)} keys")
    else:
        # 原有的数组处理逻辑
        batch_size, prediction_horizon, action_dim = action_pred_batch.shape

        # Create trajectory data dictionary
        traj_data = {
            'action_pred_batch': action_pred_batch,
            'batch_size': batch_size,
            'prediction_horizon': prediction_horizon,
            'action_dim': action_dim,
        }

        # Add additional data from kwargs
        traj_data.update(kwargs)

        # Calculate and add initial position (average of first timestep)
        if 'init_pos' not in traj_data:
            traj_data['init_pos'] = np.mean(action_pred_batch[:, 0, :], axis=0)

    # Save based on format
    if format == 'npz':
        # For npz, ensure all values are numpy arrays
        npz_data = {}
        for key, value in traj_data.items():
            if isinstance(value, (int, float)):
                npz_data[key] = np.array(value)
            elif isinstance(value, np.ndarray):
                npz_data[key] = value
            else:
                # Skip non-numeric data for npz
                print(f"⚠️  Skipping '{key}' for npz (type: {type(value)})")
                continue

        np.savez(save_path.with_suffix('.npz'), **npz_data)
        print(f"✓ Trajectory saved to {save_path.with_suffix('.npz')}")

    elif format == 'pkl':
        with open(save_path.with_suffix('.pkl'), 'wb') as f:
            pickle.dump(traj_data, f)
        print(f"✓ Trajectory saved to {save_path.with_suffix('.pkl')}")

    elif format == 'npy':
        np.save(save_path.with_suffix('.npy'), traj_data)
        print(f"✓ Trajectory saved to {save_path.with_suffix('.npy')}")

    else:
        raise ValueError(f"Unsupported format: {format}. Use 'npz', 'pkl', or 'npy'.")

    return traj_data

def load_trajectory_data(load_path, format='npz'):
    """
    Load bimanual trajectory data from local file.

    Parameters:
    - load_path: str or Path, path to the saved trajectory data
    - format: str, 'npz' (default), 'pkl', or 'npy'

    Returns:
    - dict: Dictionary containing trajectory data
    """
    load_path = Path(load_path)

    if format == 'npz':
        data = np.load(load_path.with_suffix('.npz'), allow_pickle=True)
        traj_data = {key: data[key] for key in data.files}
    elif format == 'pkl':
        with open(load_path.with_suffix('.pkl'), 'rb') as f:
            traj_data = pickle.load(f)
    elif format == 'npy':
        traj_data = np.load(load_path.with_suffix('.npy'), allow_pickle=True).item()
    else:
        raise ValueError(f"Unsupported format: {format}. Use 'npz', 'pkl', or 'npy'.")

    print(f"Trajectory data loaded from {load_path}")
    print(f"  - Batch size: {traj_data['batch_size']}")
    print(f"  - Prediction horizon: {traj_data['prediction_horizon']}")
    print(f"  - Left init pos: {traj_data['left_eef_init_pos']}")
    print(f"  - Right init pos: {traj_data['right_eef_init_pos']}")

    return traj_data


