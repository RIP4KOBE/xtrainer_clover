import numpy as np
import matplotlib.pyplot as plt
import roboticstoolbox as rtb



def forward_kinematics(joint_angles):
    """
    Compute forward kinematics (FK) to transform joint angles into end-effector positions in Cartesian space.
    This function uses a simplified FK model, which can be replaced with real FK calculations.

    Parameters:
    - joint_angles: (batch_size, prediction_horizon, 7) -> 7 joint angles per arm
    - arm: "left" or "right"

    Returns:
    - End-effector positions (batch_size, prediction_horizon, 3), representing (x, y, z) coordinates.
    """
    # load the URDF files for the left and right arms
    urdf = "assets/urdf/nova2_robot.urdf"
    xtrainer_arm = rtb.robot.ERobot.URDF(urdf)

    batch_size, prediction_horizon, _ = joint_angles.shape
    end_effector_positions = np.zeros((batch_size, prediction_horizon, 3))  # (x, y, z)

    # Simplified FK mapping (should be replaced with actual robot FK model)
    for b in range(batch_size):
        for t in range(prediction_horizon):
            angles = joint_angles[b, t, :]
            # Example FK mapping: sum of trigonometric functions of joint angles
            T_left = xtrainer_arm.fkine(angles)
            x, y, z = T_left.t
            end_effector_positions[b, t, :] = [x, y, z]

    return end_effector_positions


def visualize_trajectory(population_trajectories, best_trajectory):
    """
    Visualize the trajectories generated by Diffusion-ES.

    Parameters:
    - population_trajectories: (batch_size, prediction_horizon, 14) # 128 trajectories, each with 16 steps, 14 joint angles
    - best_trajectory: (prediction_horizon, 14) # The best trajectory (1 trajectory)
    """
    batch_size, prediction_horizon, action_dim = population_trajectories.shape

    # Separate left and right arm joint angles
    left_arm_trajectories = population_trajectories[:, :, :6]  # (batch_size, prediction_horizon, 7)
    right_arm_trajectories = population_trajectories[:, :, 7:13]  # (batch_size, prediction_horizon, 7)

    best_left_arm = best_trajectory[0][:, :6]  # (prediction_horizon, 7)
    best_right_arm = best_trajectory[0][:, 7:13]  # (prediction_horizon, 7)

    # Compute FK end-effector positions
    left_end_effector_positions = forward_kinematics(left_arm_trajectories)  # (batch_size, prediction_horizon, 3)
    right_end_effector_positions = forward_kinematics(right_arm_trajectories)

    best_left_end_effector = forward_kinematics(best_left_arm)  # (prediction_horizon, 3)
    best_right_end_effector = forward_kinematics(best_right_arm)

    # Visualization of left and right arm trajectories
    fig = plt.figure(figsize=(12, 6))

    # Left arm trajectories
    ax1 = fig.add_subplot(121, projection='3d')
    for i in range(batch_size):
        ax1.plot(left_end_effector_positions[i, :, 0],
                 left_end_effector_positions[i, :, 1],
                 left_end_effector_positions[i, :, 2],
                 color="blue", alpha=0.2)  # Semi-transparent trajectories

    # Best trajectory (left arm)
    ax1.plot(best_left_end_effector[:, 0],
             best_left_end_effector[:, 1],
             best_left_end_effector[:, 2],
             color="red", linewidth=2, label="Best Left Trajectory")

    ax1.set_title("Left Arm End-Effector Trajectories")
    ax1.set_xlabel("X")
    ax1.set_ylabel("Y")
    ax1.set_zlabel("Z")
    ax1.legend()

    # Right arm trajectories
    ax2 = fig.add_subplot(122, projection='3d')
    for i in range(batch_size):
        ax2.plot(right_end_effector_positions[i, :, 0],
                 right_end_effector_positions[i, :, 1],
                 right_end_effector_positions[i, :, 2],
                 color="green", alpha=0.2)  # Semi-transparent trajectories

    # Best trajectory (right arm)
    ax2.plot(best_right_end_effector[:, 0],
             best_right_end_effector[:, 1],
             best_right_end_effector[:, 2],
             color="red", linewidth=2, label="Best Right Trajectory")

    ax2.set_title("Right Arm End-Effector Trajectories")
    ax2.set_xlabel("X")
    ax2.set_ylabel("Y")
    ax2.set_zlabel("Z")
    ax2.legend()

    plt.tight_layout()
    plt.show()