def visualize_trajectory_with_dp_motion(left_ee_positions, right_ee_positions, best_trajectory,
                                        reference_traj_path=None):
    """
    Visualize the trajectories generated by Diffusion-ES along with reference trajectories.
    Both left and right arm trajectories are displayed in the same 3D coordinate system.

    Parameters:
    - left_ee_positions: (batch_size, prediction_horizon, 3) - Population left arm positions
    - right_ee_positions: (batch_size, prediction_horizon, 3) - Population right arm positions
    - best_trajectory: (prediction_horizon, 20) - The best trajectory
    - reference_traj_path: str - Path to reference trajectory pkl file (optional)
    """

    batch_size = left_ee_positions.shape[0]

    # Extract best trajectory positions
    best_left_ee_positions = best_trajectory[:, :3]  # (prediction_horizon, 3)
    best_right_ee_positions = best_trajectory[:, 10:13]  # (prediction_horizon, 3)
    best_left_ee_positions = np.array(best_left_ee_positions)
    best_right_ee_positions = np.array(best_right_ee_positions)

    # Load reference trajectories if provided
    left_eef_traj_batch = None
    right_eef_traj_batch = None
    ref_batch_size = 24

    if reference_traj_path:
        traj_data = load_trajectory_data(reference_traj_path, format='pkl')
        left_eef_traj_batch = traj_data['left_eef_traj_batch']
        right_eef_traj_batch = traj_data['right_eef_traj_batch']
        # ref_batch_size = traj_data['batch_size']



    # ========== Visualization of Bimanual 3D Trajectories ==========
    fig = plt.figure(facecolor='white', figsize=(14, 12))
    ax = fig.add_subplot(111, projection='3d')
    ax.set_facecolor('white')

    ax.set_title("Bimanual Trajectories: BMM vs Reference", fontsize=16, fontweight='bold', pad=20)
    ax.set_xlabel("X (m)", fontsize=14, labelpad=10)
    ax.set_ylabel("Y (m)", fontsize=14, labelpad=10)
    ax.set_zlabel("Z (m)", fontsize=14, labelpad=10)
    ax.grid(True, alpha=0.3, linestyle='--', linewidth=0.5)

    # ===== Plot DP Population Trajectories =====
    # Left arm population (semi-transparent pink)
    for i in range(ref_batch_size):
        ax.plot(left_eef_traj_batch[i, :, 0],
                left_eef_traj_batch[i, :, 1],
                left_eef_traj_batch[i, :, 2],
                color='gray', alpha=0.2, linewidth=3.5,
                label="" if i == 0 else "")

    # Right arm population (semi-transparent green)
    for i in range(ref_batch_size):
        ax.plot(right_eef_traj_batch[i, :, 0],
                right_eef_traj_batch[i, :, 1],
                right_eef_traj_batch[i, :, 2],
                color='gray', alpha=0.2, linewidth=3.5,
                label="" if i == 0 else "")

    # ===== Define Two Keypoints =====
    keypoint1 = np.array([-0.16, -0.365, 0.18])
    keypoint2 = np.array([0.16, -0.365, 0.18])  # 如果两个点不同，请修改这里的坐标

    # ===== Plot Two Keypoints as Stars =====
    ax.scatter(keypoint1[0], keypoint1[1], keypoint1[2],
               marker='*', s=500, color='gold',
               edgecolors='darkorange', linewidths=2,
               label='', zorder=15, alpha=1.0)

    ax.scatter(keypoint2[0], keypoint2[1], keypoint2[2],
               marker='*', s=500, color='gold',
               edgecolors='darkorange', linewidths=2,
               zorder=15, alpha=1.0)

    # ===== Draw Obstacle Grid Rectangle =====
    # 两个keypoint作为长方形上方长边的两个顶点
    # 下方长边与xy平面相交（z=0）
    # 整体面对xz平面（在yz平面内展开）

    # 上方两个顶点（keypoints）
    top_left = keypoint1
    top_right = keypoint2

    # 下方两个顶点（z=0，与xy平面相交）
    bottom_left = np.array([top_left[0], top_left[1], 0.09])
    bottom_right = np.array([top_right[0], top_right[1], 0.09])

    # 构建矩形的4个顶点
    rect_vertices = np.array([
        bottom_left,  # 0: 左下
        bottom_right,  # 1: 右下
        top_right,  # 2: 右上
        top_left  # 3: 左上
    ])

    # ===== 绘制深灰色网格矩形 =====
    from mpl_toolkits.mplot3d.art3d import Poly3DCollection

    # 绘制矩形的4条边框（深灰色粗线）
    edges = [
        [0, 1],  # 底边
        [1, 2],  # 右边
        [2, 3],  # 顶边
        [3, 0]  # 左边
    ]

    for edge in edges:
        points = [rect_vertices[edge[0]], rect_vertices[edge[1]]]
        points = np.array(points)
        ax.plot3D(points[:, 0], points[:, 1], points[:, 2],
                  color='#505050', linewidth=3, alpha=0.9, zorder=5)

    # 绘制半透明深灰色面
    face = [rect_vertices[0], rect_vertices[1], rect_vertices[2], rect_vertices[3]]
    face_collection = Poly3DCollection([face], alpha=0.25,
                                       facecolor='#505050',
                                       edgecolor='none', zorder=5)
    ax.add_collection3d(face_collection)

    # 绘制网格线（在矩形内部添加横向和纵向网格）
    num_grid_lines = 8

    # 纵向网格线（从下到上）
    for i in range(1, num_grid_lines):
        t = i / num_grid_lines
        # 线性插值计算网格点
        point1 = bottom_left + t * (top_left - bottom_left)
        point2 = bottom_right + t * (top_right - bottom_right)
        ax.plot3D([point1[0], point2[0]],
                  [point1[1], point2[1]],
                  [point1[2], point2[2]],
                  color='#707070', linewidth=1, alpha=0.5, zorder=5)

    # 横向网格线（从左到右）
    for i in range(1, num_grid_lines):
        t = i / num_grid_lines
